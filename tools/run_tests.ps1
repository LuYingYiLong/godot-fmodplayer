param(
    [ValidateSet('profile', 'spectrum', 'reverb', 'capture', 'all', 'regression', 'smoke', 'editor', 'routing', 'spatial')]
    [string]$Suite = 'all',
    [ValidatePattern('^[a-zA-Z0-9_-]+$')]
    [string]$Label = 'run',
    [string]$GodotPath = 'C:/Users/Administrator/Documents/Godot/Godot_v4.7.2-stable_win64.exe',
    [string]$FmodRuntime,
    [string]$ExtensionBin,
    [switch]$PrepareOnly,
    [switch]$Import,
    [switch]$Quick,
    [switch]$CaptureBaseline
)

$ErrorActionPreference = 'Stop'
if ($CaptureBaseline -and $Suite -ne 'capture') { throw '-CaptureBaseline requires -Suite capture' }
function Get-TestFileHash([string]$Path) {
    $stream = [System.IO.File]::OpenRead($Path)
    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    try {
        return [System.BitConverter]::ToString($sha256.ComputeHash($stream)).Replace('-', '')
    } finally {
        $sha256.Dispose()
        $stream.Dispose()
    }
}
function Sync-TestFile([string]$SourcePath, [string]$TargetPath) {
    if ((Test-Path -LiteralPath $TargetPath) -and
        ((Get-TestFileHash $SourcePath) -eq (Get-TestFileHash $TargetPath))) {
        return
    }
    Copy-Item -LiteralPath $SourcePath -Destination $TargetPath -Force
}
function Invoke-TestProcess([string]$Executable, [string[]]$Arguments, [string]$ConsoleLog) {
    # Windows PowerShell treats redirected native stderr as PowerShell errors.
    # Let Godot finish and use its exit code, as PowerShell 7 does.
    $ErrorActionPreference = 'Continue'
    & $Executable @Arguments *> $ConsoleLog
    if ($LASTEXITCODE -ne 0) { throw "Godot failed ($LASTEXITCODE); see $ConsoleLog" }
    if (Select-String -LiteralPath $ConsoleLog -Pattern '^(SCRIPT ERROR:|ERROR:)' -Quiet) {
        throw "Godot reported an error; see $ConsoleLog"
    }
}
$repoRoot = Split-Path -Parent $PSScriptRoot
$testRoot = Join-Path $repoRoot 'tests'
$addonSource = Join-Path $repoRoot 'addons/fmod_player'
$addonRoot = Join-Path $testRoot 'addons/fmod_player'
$binRoot = Join-Path $addonRoot 'bin'
$extensionResource = 'res://addons/fmod_player/bin/fmod_player.gdextension'
if (-not $ExtensionBin) { $ExtensionBin = Join-Path $addonSource 'bin' }
$ExtensionBin = [System.IO.Path]::GetFullPath($ExtensionBin)
$runName = $Label + '_' + (Get-Date -Format 'yyyyMMdd_HHmmss_fff')
$logRoot = Join-Path $testRoot ('logs/runs/' + $runName)
New-Item -ItemType Directory -Path $binRoot, $logRoot -Force | Out-Null
[System.IO.File]::WriteAllText((Join-Path $testRoot 'logs/.gdignore'), '')
$consoleGodot = Join-Path (Split-Path -Parent $GodotPath) (([System.IO.Path]::GetFileNameWithoutExtension($GodotPath)) + '_console.exe')
if (Test-Path -LiteralPath $consoleGodot) { $GodotPath = $consoleGodot }
if (-not $FmodRuntime) {
    $FmodRuntime = Join-Path $repoRoot 'src/thirdparty/fmod/lib/x64/fmod.dll'
}
if (-not (Test-Path -LiteralPath $FmodRuntime)) {
    throw 'FMOD runtime missing. Pass -FmodRuntime with your locally installed SDK fmod.dll path.'
}
# Deploy the complete plugin, preserving its original relative resource paths.
foreach ($directory in Get-ChildItem -LiteralPath $addonSource -Directory -Recurse -Force) {
    if ($directory.FullName -match '[\\/]__pycache__([\\/]|$)') { continue }
    $relativePath = $directory.FullName.Substring($addonSource.Length + 1)
    New-Item -ItemType Directory -Path (Join-Path $addonRoot $relativePath) -Force | Out-Null
}
foreach ($file in Get-ChildItem -LiteralPath $addonSource -File -Recurse -Force) {
    if ($file.FullName -match '[\\/]__pycache__([\\/]|$)' -or $file.Extension -eq '.pyc') { continue }
    $relativePath = $file.FullName.Substring($addonSource.Length + 1)
    Sync-TestFile $file.FullName (Join-Path $addonRoot $relativePath)
}
# Migrate files generated by the former binaries-only test deployment.
foreach ($legacyPath in @('fmod_player.gdextension', 'fmod_player.gdextension.uid', 'bin/.gdignore',
    'translations/fmod_property_translations.gd', 'translations/fmod_property_translations.gd.uid',
    'tools/property_translation_generator.gd', 'tools/property_translation_generator.gd.uid',
    'tools/generate_property_translations_scene.gd', 'tools/generate_property_translations_scene.gd.uid',
    'tools/__pycache__')) {
    $legacyFile = Join-Path $addonRoot $legacyPath
    if (Test-Path -LiteralPath $legacyFile) {
        $legacyResolved = [System.IO.Path]::GetFullPath($legacyFile)
        $legacyDestination = [System.IO.Path]::GetFullPath((Join-Path $logRoot ([System.IO.Path]::GetFileName($legacyFile))))
        if (-not $legacyResolved.StartsWith([System.IO.Path]::GetFullPath($addonRoot) + [System.IO.Path]::DirectorySeparatorChar) -or
            -not $legacyDestination.StartsWith([System.IO.Path]::GetFullPath($logRoot) + [System.IO.Path]::DirectorySeparatorChar)) {
            throw 'Legacy addon cleanup escaped the staging or log directory.'
        }
        Move-Item -LiteralPath $legacyResolved -Destination $legacyDestination
    }
}
foreach ($extension in @('.dll', '.pdb')) {
    $fileName = 'fmod_player.windows.template_debug.x86_64' + $extension
    $sourceFile = Join-Path $ExtensionBin $fileName
    if ($extension -eq '.pdb' -and -not (Test-Path -LiteralPath $sourceFile)) {
        $staleSymbols = Join-Path $binRoot $fileName
        if (Test-Path -LiteralPath $staleSymbols) {
            Move-Item -LiteralPath $staleSymbols -Destination (Join-Path $logRoot $fileName)
        }
        continue
    }
    Sync-TestFile $sourceFile (Join-Path $binRoot $fileName)
}
Sync-TestFile $FmodRuntime (Join-Path $binRoot 'fmod.dll')
$symbolsPath = Join-Path $binRoot 'fmod_player.windows.template_debug.x86_64.pdb'
$symbolsHash = if (Test-Path -LiteralPath $symbolsPath) { Get-TestFileHash $symbolsPath } else { $null }
$buildInfo = @{
    suite = $Suite
    quick = [bool]$Quick
    capture_baseline = [bool]$CaptureBaseline
    extension_source = $ExtensionBin
    dll_sha256 = Get-TestFileHash (Join-Path $binRoot 'fmod_player.windows.template_debug.x86_64.dll')
    pdb_sha256 = $symbolsHash
}
$buildInfo | ConvertTo-Json | Set-Content -LiteralPath (Join-Path $logRoot 'build.json') -Encoding utf8
Push-Location $repoRoot
try {
    $extensionList = Join-Path $testRoot '.godot/extension_list.cfg'
    $needsImport = -not (Test-Path -LiteralPath $extensionList)
    if (-not $needsImport) {
        $needsImport = -not (Select-String -LiteralPath $extensionList -SimpleMatch $extensionResource -Quiet)
    }
    if ($Import -or $needsImport) {
        if ($needsImport -and (Test-Path -LiteralPath $extensionList)) {
            # Godot loads cached extensions before scanning their new locations.
            Move-Item -LiteralPath $extensionList -Destination (Join-Path $logRoot 'extension_list.before.cfg')
        }
        # A fresh checkout has no UID cache when Godot first reads the main scene.
        $projectPath = Join-Path $testRoot 'project.godot'
        $originalProject = [System.IO.File]::ReadAllBytes($projectPath)
        try {
            $projectText = [System.Text.Encoding]::UTF8.GetString($originalProject)
            $projectText = [regex]::Replace($projectText, '(?m)^run/main_scene=.*$', 'run/main_scene="res://main.tscn"')
            [System.IO.File]::WriteAllText($projectPath, $projectText, [System.Text.UTF8Encoding]::new($false))
            Invoke-TestProcess $GodotPath @('--headless', '--path', $testRoot, '--editor', '--import', 'res://runner/automated.tscn', '--log-file', (Join-Path $logRoot 'import.log')) (Join-Path $logRoot 'import-console.log')
        } finally {
            [System.IO.File]::WriteAllBytes($projectPath, $originalProject)
        }
    }
    if (-not $PrepareOnly) {
        if ($Suite -eq 'editor') {
            Invoke-TestProcess 'python' @((Join-Path $PSScriptRoot 'run_editor_tests.py'), '--godot', $GodotPath, '--output-dir', $logRoot) (Join-Path $logRoot 'console.log')
        } else {
            $testArguments = @('--headless', '--path', $testRoot, 'res://runner/automated.tscn', '--log-file', (Join-Path $logRoot 'godot.log'), '--', "--suite=$Suite", "--output-dir=$logRoot")
            if ($Quick) { $testArguments += '--quick' }
            if ($CaptureBaseline) { $testArguments += '--capture-baseline' }
            Invoke-TestProcess $GodotPath $testArguments (Join-Path $logRoot 'console.log')
        }
        if (-not (Select-String -LiteralPath (Join-Path $logRoot 'godot.log') -SimpleMatch 'TESTS_PASSED' -Quiet)) {
            throw "Test completion marker missing; see $logRoot"
        }
    }
    Write-Output "Test output: $logRoot"
} finally {
    Pop-Location
}
